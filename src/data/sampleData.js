// LocalStorage keys
const STORAGE_KEYS = {
  sections: 'wash_fold_oms_sections',
  products: 'wash_fold_oms_products',
  customers: 'wash_fold_oms_customers',
  orders: 'wash_fold_oms_orders',
  paymentMethods: 'wash_fold_oms_payment_methods',
  initialized: 'wash_fold_oms_initialized',
};

// Initialize localStorage with sample data if empty
export const initializeSampleData = () => {
  const isInitialized = localStorage.getItem(STORAGE_KEYS.initialized);
  
  if (!isInitialized) {
    localStorage.setItem(STORAGE_KEYS.sections, JSON.stringify(sampleSections));
    localStorage.setItem(STORAGE_KEYS.products, JSON.stringify(sampleProducts));
    localStorage.setItem(STORAGE_KEYS.customers, JSON.stringify(sampleCustomers));
    localStorage.setItem(STORAGE_KEYS.orders, JSON.stringify(sampleOrders));
    localStorage.setItem(STORAGE_KEYS.paymentMethods, JSON.stringify(samplePaymentMethods));
    localStorage.setItem(STORAGE_KEYS.initialized, 'true');
    console.log('Sample data initialized in localStorage');
  }
};

// Load data from localStorage
export const loadFromLocalStorage = () => {
  initializeSampleData();
  
  return {
    sections: JSON.parse(localStorage.getItem(STORAGE_KEYS.sections) || '[]'),
    products: JSON.parse(localStorage.getItem(STORAGE_KEYS.products) || '[]'),
    customers: JSON.parse(localStorage.getItem(STORAGE_KEYS.customers) || '[]'),
    orders: JSON.parse(localStorage.getItem(STORAGE_KEYS.orders) || '[]'),
    paymentMethods: JSON.parse(localStorage.getItem(STORAGE_KEYS.paymentMethods) || '[]'),
  };
};

// Save data to localStorage
export const saveToLocalStorage = (key, data) => {
  const storageKey = STORAGE_KEYS[key];
  if (storageKey) {
    localStorage.setItem(storageKey, JSON.stringify(data));
  }
};

// Clear all sample data
export const clearSampleData = () => {
  Object.values(STORAGE_KEYS).forEach(key => localStorage.removeItem(key));
  console.log('Sample data cleared from localStorage');
};
